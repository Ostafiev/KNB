import { HAND_EMOJI } from '../lib/game'
import type { HandChoice } from '../types'

export type HandSide = 'left' | 'right'

/**
 * Рука в арене боя.
 *
 * Обе руки — зеркальное отражение друг друга, как в жизни: два человека сидят
 * напротив и выбрасывают правую руку.
 *
 * Три слоя, и каждый нужен:
 *
 *   внешний  — отражение по горизонтали для левой руки;
 *   средний  — сюда приходит анимация (тряска, столкновение, парение);
 *   внутренний — постоянный разворот эмодзи на 90°.
 *
 * Порядок именно такой из-за замаха. Раньше отражение и разворот стояли вместе
 * на внутреннем слое, а тряска — снаружи, и получалось, что зеркалится только
 * картинка, а движение у обеих рук идёт в одну сторону: руки замахивались
 * синхронно, как у одного человека, а не навстречу друг другу. Теперь
 * отражение лежит НАД анимацией и переворачивает вместе с рукой и её замах.
 *
 * Разделение на слои нужно и по другой причине: анимация задаёт свойство
 * transform целиком и стёрла бы любой поворот, записанный на том же элементе.
 */
export function Hand({
  choice,
  side,
  className = '',
  style,
}: {
  choice: HandChoice
  side: HandSide
  className?: string
  style?: React.CSSProperties
}) {
  return (
    <span
      style={{
        display: 'inline-block',
        transform: side === 'left' ? 'scaleX(-1)' : undefined,
      }}
    >
      <span
        className={className}
        style={{
          display: 'inline-block',
          /*
           * Ось вращения — запястье, а не середина ладони.
           *
           * Эмодзи развёрнут на 90° влево, поэтому запястье оказывается у
           * правого края. Замах вокруг центра выглядел кувырком: кисть
           * уезжала вбок вместе с костяшками. Вокруг запястья это тот самый
           * жест на счёт «раз-два-три».
           *
           * Значение одно на обе руки: левую целиком отражает внешний слой,
           * и «право» в её собственных координатах — это «лево» на экране.
           */
          transformOrigin: '78% 50%',
          ...style,
        }}
      >
        <span style={{ display: 'inline-block', transform: 'rotate(-90deg)' }}>
          {HAND_EMOJI[choice]}
        </span>
      </span>
    </span>
  )
}
