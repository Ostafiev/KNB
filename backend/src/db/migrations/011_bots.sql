/*
 * Боты.
 *
 * Бот — это обычный игрок в таблице users с пометкой is_bot. Так он попадает
 * во все те же механизмы: ставка списывается через журнал, матч пишется
 * в историю, раунды сохраняются с фигурами и временем. Отдельной «ветки для
 * ботов» в игровой логике нет — иначе однажды она разошлась бы с настоящей.
 *
 * Из отчётов боты исключаются: их баланс не имеет отношения к экономике
 * живых игроков, и считать его вместе с людьми значило бы обманывать себя.
 */

ALTER TABLE users
  ADD COLUMN is_bot BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX users_bots_idx ON users (is_bot) WHERE is_bot = TRUE;

/*
 * Настройки ботов. Живут там же, где параметры экономики, — правятся
 * из админки без пересборки.
 *
 * bots_enabled — рубильник. Пока игроков мало, включён; когда людей станет
 *   достаточно, выключается одним нажатием.
 * bots_open_matches — сколько открытых боёв боты держат в списке.
 * bots_move_min_ms / bots_move_max_ms — разброс задержки хода. Бот думает
 *   как человек, но никогда не пропускает ход: раунд всегда доигрывается.
 */
INSERT INTO app_config (key, value, description) VALUES
  ('bots_enabled',      '1',    'Боты включены: 1 — да, 0 — нет'),
  ('bots_open_matches', '3',    'Сколько открытых боёв держат боты'),
  ('bots_min_bet',      '25',   'Минимальная ставка бота'),
  ('bots_max_bet',      '100',  'Максимальная ставка бота'),
  ('bots_move_min_ms',  '1500', 'Минимальная задержка хода бота'),
  ('bots_move_max_ms',  '7000', 'Максимальная задержка хода бота')
ON CONFLICT (key) DO NOTHING;
