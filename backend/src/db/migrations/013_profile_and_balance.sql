/*
 * Знакомство и стартовый баланс.
 *
 * 1. Имя игрока.
 *
 * До сих пор ник подставлялся из Telegram молча. Человек мог не хотеть,
 * чтобы в игре светилось его настоящее имя, — и узнавал об этом, только
 * увидев себя в списке соперников. Теперь при первом входе он выбирает имя
 * сам, а отметка о том, что знакомство прошло, живёт на сервере: со сменой
 * телефона спрашивать заново незачем.
 *
 * 2. Стартовый баланс.
 *
 * Ста медяков хватало на четыре ставки по двадцать пять — человек мог
 * остаться ни с чем, толком не начав. Тысяча даёт запас на вечер игры.
 */

ALTER TABLE users
  ADD COLUMN profile_ready_at TIMESTAMPTZ;

/*
 * Тем, кто уже играл, знакомство показывать не надо: они своё имя видели
 * и при желании меняли в профиле.
 */
UPDATE users
   SET profile_ready_at = COALESCE(consent_accepted_at, created_at)
 WHERE consent_accepted_at IS NOT NULL;

UPDATE app_config
   SET value = '1000',
       description = 'Бонус новому игроку'
 WHERE key = 'signup_bonus';
