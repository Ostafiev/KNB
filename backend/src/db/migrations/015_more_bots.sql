-- Больше открытых боёв и вся линейка ставок.
--
-- В базе стояло bots_open_matches = 3 и bots_max_bet = 100. Настройка из базы
-- перебивает значения по умолчанию в коде, поэтому список открытых боёв
-- оставался коротким, а ставок выше сотни в нём не бывало вовсе: человек,
-- выбравший 250 или 500, ждал соперника, которого никто не собирался открывать.
--
-- Двенадцати боёв хватает, чтобы закрыть основные сочетания «ставка × раунды»
-- и человек находил бой сразу. Ставка при этом не удерживается, пока бой не
-- начался, так что открытые бои ничего не стоят.

UPDATE app_config SET value = '12'::jsonb  WHERE key = 'bots_open_matches';
UPDATE app_config SET value = '500'::jsonb WHERE key = 'bots_max_bet';

-- Если строк почему-то нет (база заведена раньше этих ключей) — заводим.
INSERT INTO app_config (key, value)
VALUES ('bots_open_matches', '12'::jsonb), ('bots_max_bet', '500'::jsonb)
ON CONFLICT (key) DO NOTHING;
