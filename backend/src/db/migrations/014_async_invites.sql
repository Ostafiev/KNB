/*
 * Приглашение, которое можно не караулить.
 *
 * Раньше приглашение другу работало так: отправил ссылку — и сиди на экране
 * ожидания. Уйдёшь — матч засчитается брошенным. А друг может открыть ссылку
 * через час, когда освободится, и это нормально.
 *
 * Теперь у приглашения две отметки готовности — по одной на каждого. Бой
 * начинается, когда оба отметились и оба у экрана. До этого приглашение
 * просто лежит и ждёт: ставка не списана, никто ничего не теряет.
 *
 * snoozed_until — «сейчас неудобно». Друг принял вызов, а человек занят:
 * он нажимает «позже», и окно перестаёт всплывать на какое-то время.
 * Без этого приглашение превращалось бы в назойливое напоминание.
 */

ALTER TABLE matches
  ADD COLUMN host_ready_at  TIMESTAMPTZ,
  ADD COLUMN guest_ready_at TIMESTAMPTZ,
  ADD COLUMN snoozed_until  TIMESTAMPTZ;

/* Приглашения, ждущие ответа, — их разбирает фоновая уборка и экраны игроков. */
CREATE INDEX matches_invite_waiting_idx
  ON matches (status, guest_ready_at)
  WHERE status = 'pending';
