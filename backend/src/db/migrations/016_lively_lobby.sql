-- Список боёв должен выглядеть людным.
--
-- В базе после миграции 015 стояло bots_open_matches = 12. Найти бой по этому
-- списку можно, но выглядит он полупустым: двенадцать строк на весь экран
-- читаются как «здесь никого нет», и это первое, что видит новый человек.
--
-- Тридцать шесть — это все сочетания «ставка × раунды», какие вообще можно
-- выбрать в приложении, и каждое примерно по разу с небольшим запасом. Плюс
-- к этому боты теперь понемногу закрывают свои заявки и открывают новые, так
-- что состав списка меняется сам собой.
--
-- Открытая заявка ничего не стоит: ставка удерживается только когда бой начался.

UPDATE app_config SET value = '36'::jsonb WHERE key = 'bots_open_matches';

INSERT INTO app_config (key, value)
VALUES ('bots_open_matches', '36'::jsonb)
ON CONFLICT (key) DO NOTHING;
